package ai.agent;

import ai.model.ReviewResult;
import ai.model.TestCase;
import ai.tool.JiraRequirementTool;
import org.testng.Assert;
import org.testng.annotations.Test;

import java.util.List;

public class TestDataIdentifierAgentTest {

    @Test
    public void generateTestDataFromAgent1AndAgent2() {

        // =====================================================
        // Create Agents
        // =====================================================

        TestCaseGenerationAgent generationAgent =
                new TestCaseGenerationAgent();

        TestCaseReviewAgent reviewAgent =
                new TestCaseReviewAgent();

        TestDataIdentifierAgent dataAgent =
                new TestDataIdentifierAgent();

        JiraRequirementTool jiraRequirementTool =
                new JiraRequirementTool();

        try {

            // =====================================================
            // STEP 1: Get requirement from Jira
            // =====================================================

            System.out.println(
                    "========================================"
            );

            System.out.println(
                    "STEP 1 - GET JIRA REQUIREMENT"
            );

            System.out.println(
                    "========================================"
            );

            String requirementText =
                    jiraRequirementTool.getRequirementText("SCRUM-5");

            Assert.assertNotNull(requirementText);
            Assert.assertFalse(requirementText.isBlank());

            System.out.println(requirementText);


            // =====================================================
            // STEP 2: Agent 1 generates test cases
            // =====================================================

            System.out.println(
                    "========================================"
            );

            System.out.println(
                    "STEP 2 - AGENT 1: GENERATE TEST CASES"
            );

            System.out.println(
                    "========================================"
            );

            List<TestCase> testCases =
                    generationAgent.generateTestCasesFromJira(
                            "SCRUM-5"
                    );

            Assert.assertNotNull(testCases);
            Assert.assertFalse(testCases.isEmpty());

            System.out.println(
                    "Agent 1 generated "
                            + testCases.size()
                            + " test case(s)."
            );

            for (TestCase testCase : testCases) {

                System.out.println(testCase);
            }


            // =====================================================
            // STEP 3: Agent 2 reviews Agent 1 test cases
            // =====================================================

            System.out.println(
                    "========================================"
            );

            System.out.println(
                    "STEP 3 - AGENT 2: REVIEW TEST CASES"
            );

            System.out.println(
                    "========================================"
            );

            ReviewResult reviewResult =
                    reviewAgent.review(
                            requirementText,
                            testCases
                    );

            Assert.assertNotNull(reviewResult);
            Assert.assertNotNull(
                    reviewResult.getOverallStatus()
            );
            Assert.assertNotNull(
                    reviewResult.getSummary()
            );

            System.out.println(
                    "Agent 2 Review Result:"
            );

            System.out.println(reviewResult);


            // =====================================================
            // STEP 4: Pass Agent 1 test cases to Agent 3
            // =====================================================

            System.out.println(
                    "========================================"
            );

            System.out.println(
                    "STEP 4 - AGENT 3: IDENTIFY TEST DATA"
            );

            System.out.println(
                    "========================================"
            );

            /*
             * Agent 2 currently returns ReviewResult.
             *
             * It does not modify the List<TestCase>.
             *
             * Therefore Agent 3 consumes the same test cases
             * generated by Agent 1 after Agent 2 has reviewed them.
             */

            String generatedData =
                    dataAgent.generateData(testCases);

            Assert.assertNotNull(generatedData);
            Assert.assertFalse(generatedData.isBlank());

            System.out.println(
                    "Agent 3 Data Requirements:"
            );

            System.out.println(generatedData);


            // =====================================================
            // STEP 5: Agent 3 generates synthetic test data
            // =====================================================

            System.out.println(
                    "========================================"
            );

            System.out.println(
                    "STEP 5 - AGENT 3: GENERATE SYNTHETIC DATA"
            );

            System.out.println(
                    "========================================"
            );

            String syntheticData =
                    dataAgent.generateSyntheticData(
                            generatedData
                    );

            Assert.assertNotNull(syntheticData);
            Assert.assertFalse(syntheticData.isBlank());

            System.out.println(
                    "Final Synthetic Test Data:"
            );

            System.out.println(syntheticData);


            // =====================================================
            // STEP 6: Pipeline completed
            // =====================================================

            System.out.println(
                    "========================================"
            );

            System.out.println(
                    "AGENT 1 → AGENT 2 → AGENT 3 PIPELINE COMPLETE"
            );

            System.out.println(
                    "========================================"
            );

        } finally {

            // Close Agent 2 Ollama client
            reviewAgent.close();

            // Close Agent 3 Ollama client
            dataAgent.close();
        }
    }
}